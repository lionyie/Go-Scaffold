#!/usr/bin/env node
// Generates the HTTP operation catalog from the OpenAPI spec plus the Kratos
// operation constants, so the admin UI can list every protected endpoint.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import process from 'node:process'

const ROOT = process.cwd()
const OPENAPI = path.join(ROOT, 'packages', 'api-client', 'generated', 'openapi.yaml')
const API_DIR = path.join(ROOT, 'services', 'api')
const OUT = path.join(ROOT, 'services', 'internal', 'pkg', 'operations', 'operations_gen.go')

function walk(dir) {
  if (!existsSync(dir)) return []
  const out = []
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) out.push(...walk(full))
    else out.push(full)
  }
  return out
}

// Kratos operation names look like /identity.v1.RoleService/ListRoles.
const operations = new Map()
for (const file of walk(API_DIR)) {
  if (!file.endsWith('_http.pb.go')) continue
  const source = readFileSync(file, 'utf8')
  for (const match of source.matchAll(/Operation[A-Za-z0-9_]+\s*=\s*"([^"]+)"/g)) {
    const name = match[1]
    const slash = name.lastIndexOf('/')
    if (slash <= 0) continue
    const servicePart = name.slice(1, slash)
    const method = name.slice(slash + 1)
    const service = servicePart.slice(servicePart.lastIndexOf('.') + 1)
    operations.set(`${service}_${method}`, { name, service })
  }
}

if (operations.size === 0) {
  console.error('genoperations: no Kratos operations found')
  process.exit(1)
}

const lines = readFileSync(OPENAPI, 'utf8').split(/\r?\n/)
const catalog = []
let currentPath = ''
let currentMethod = ''
for (const line of lines) {
  let match = line.match(/^ {4}(\/[^:]+):\s*$/)
  if (match) {
    currentPath = match[1]
    currentMethod = ''
    continue
  }
  match = line.match(/^ {8}(get|post|put|delete|patch):\s*$/)
  if (match) {
    currentMethod = match[1].toUpperCase()
    continue
  }
  match = line.match(/^ {12}operationId:\s*(\S+)\s*$/)
  if (match) {
    const info = operations.get(match[1])
    if (info) {
      catalog.push({ name: info.name, service: info.service, method: currentMethod, path: currentPath })
    } else {
      console.warn(`genoperations: no Kratos operation for ${match[1]} (${currentMethod} ${currentPath})`)
    }
    currentMethod = ''
  }
}

if (catalog.length === 0) {
  console.error('genoperations: generated an empty catalog')
  process.exit(1)
}

catalog.sort((a, b) => a.name.localeCompare(b.name))

const quote = (value) => JSON.stringify(value)

const body = catalog
  .map(
    (entry) =>
      `\t{Name: ${quote(entry.name)}, Service: ${quote(entry.service)}, Method: ${quote(entry.method)}, Path: ${quote(entry.path)}},`,
  )
  .join('\n')

const output = `// Code generated by scripts/genoperations.mjs. DO NOT EDIT.

package operations

// Operation describes one HTTP endpoint exposed by the server.
type Operation struct {
\tName    string
\tService string
\tMethod  string
\tPath    string
}

// All lists every generated HTTP operation in lexical order.
var All = []Operation{
${body}
}
`

mkdirSync(path.dirname(OUT), { recursive: true })
writeFileSync(OUT, output)
console.log(`genoperations: wrote ${catalog.length} operations`)
