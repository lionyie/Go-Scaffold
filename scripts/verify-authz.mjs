#!/usr/bin/env node
import { existsSync, readFileSync, readdirSync } from 'node:fs'
import path from 'node:path'
import process from 'node:process'

const ROOT = process.cwd()
const API_DIR = path.join(ROOT, 'services', 'api')
const MAPPING = path.join(ROOT, 'services', 'internal', 'server', 'authz', 'mapping.go')
const EXTENSIONS = path.join(ROOT, 'services', 'internal', 'server', 'authz', 'extensions_gen.go')
const PERMISSIONS = path.join(ROOT, 'contracts', 'permissions.yaml')
const PERMISSIONS_GO = path.join(ROOT, 'services', 'internal', 'pkg', 'rbac', 'permissions_gen.go')

function walk(dir) {
  if (!existsSync(dir)) return []
  const out = []
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) out.push(...walk(full))
    else out.push(full)
  }
  return out
}

function text(file) {
  return existsSync(file) ? readFileSync(file, 'utf8') : ''
}

// 1. Operations generated by protoc-gen-go-http.
const generated = new Set()
for (const file of walk(API_DIR)) {
  if (!file.endsWith('_http.pb.go')) continue
  const source = readFileSync(file, 'utf8')
  for (const match of source.matchAll(/(Operation[A-Za-z0-9_]+)\s*=\s*"([^"]+)"/g)) {
    generated.add(match[1])
  }
}

// 2. Permission codes from the catalog and generated constants.
const catalog = new Set()
for (const match of text(PERMISSIONS).matchAll(/^\s*-?\s*code:\s*["']?([^"'\s]+)/gm)) {
  catalog.add(match[1])
}
const permissionConsts = new Map()
for (const match of text(PERMISSIONS_GO).matchAll(/^\s*(Perm[A-Za-z0-9_]+)\s*=\s*"([^"]+)"/gm)) {
  permissionConsts.set(match[1], match[2])
  catalog.add(match[2])
}

// 3. Requirements registered by hand-written and generated files.
const requirements = new Map()
function collect(source, pattern, file) {
  for (const match of source.matchAll(pattern)) {
    const operation = match[1]
    const body = match[2] ?? ''
    const publicRule = /Public:\s*true/.test(body)
    const codeMatch = body.match(/Code:\s*(?:rbac\.)?(?:Perm([A-Za-z0-9_]+)|"([^"]*)")/)
    let code = ''
    if (codeMatch && !publicRule) {
      if (codeMatch[2] !== undefined) code = codeMatch[2]
      else code = permissionConsts.get(`Perm${codeMatch[1]}`) ?? `UNKNOWN(Perm${codeMatch[1]})`
    }
    requirements.set(operation, { public: publicRule, code, file })
  }
}

collect(text(MAPPING), /(?:[a-z0-9]+\.)?(Operation[A-Za-z0-9_]+)\s*:\s*\{([^}]*)\}/g, 'mapping.go')
collect(
  text(EXTENSIONS),
  /Requirements\[\s*(?:[a-z0-9]+\.)?(Operation[A-Za-z0-9_]+)\s*\]\s*=\s*Requirement\{([^}]*)\}/g,
  'extensions_gen.go',
)

const missing = [...generated].filter((operation) => !requirements.has(operation)).sort()
const stale = [...requirements.keys()].filter((operation) => !generated.has(operation)).sort()
const badCodes = []
for (const [operation, rule] of requirements) {
  if (rule.code && !catalog.has(rule.code)) {
    badCodes.push(`${operation} -> ${rule.code} (${rule.file})`)
  }
}

if (missing.length || stale.length || badCodes.length) {
  console.error('authz verification failed')
  if (missing.length) console.error(`\nmissing requirements:\n  ${missing.join('\n  ')}`)
  if (stale.length) console.error(`\nstale requirements:\n  ${stale.join('\n  ')}`)
  if (badCodes.length) console.error(`\nunknown permission codes:\n  ${badCodes.join('\n  ')}`)
  process.exit(1)
}

console.log(`authz ok: ${generated.size} operations, ${requirements.size} requirements, ${catalog.size} permissions`)
