#!/usr/bin/env node
import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs'
import path from 'node:path'
import process from 'node:process'

const ROOT = process.cwd()
const EXT_DIR = path.join(ROOT, 'extensions')
const TEMPLATES = path.join(EXT_DIR, 'templates')
const LOCKFILE = path.join(EXT_DIR, 'installed.lock.json')
const UPSTREAM = path.join(EXT_DIR, 'upstream.json')
const LOCK = path.join(EXT_DIR, '.lock')
const TMP = path.join(ROOT, '.scaffold-tmp')
const SCAFFOLD = JSON.parse(readFileSync(path.join(ROOT, 'scaffold.json'), 'utf8'))
const MODULE = SCAFFOLD.module

const GENERATED = {
  oauth: 'services/internal/auth/oauthproviders_gen/providers_gen.go',
  extensions: 'services/internal/extensions/registry_gen/registry_gen.go',
  authz: 'services/internal/server/authz/extensions_gen.go',
  admin: 'apps/admin/src/router/features.gen.ts',
  web: 'apps/web/src/router/features.gen.ts',
}

function fail(message) {
  console.error(`module: ${message}`)
  process.exit(1)
}

function readJSON(file, fallback) {
  if (!existsSync(file)) return fallback
  return JSON.parse(readFileSync(file, 'utf8'))
}

function writeJSON(file, value) {
  mkdirSync(path.dirname(file), { recursive: true })
  writeFileSync(file, `${JSON.stringify(value, null, 2)}\n`)
}

function writeIfChanged(file, content) {
  mkdirSync(path.dirname(file), { recursive: true })
  if (existsSync(file) && readFileSync(file, 'utf8') === content) return
  writeFileSync(file, content)
}

function hashFile(file) {
  return createHash('sha256').update(readFileSync(file)).digest('hex')
}

function walk(dir) {
  const out = []
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) out.push(...walk(full))
    else out.push(full)
  }
  return out
}

function templateHash(dir) {
  const hash = createHash('sha256')
  for (const file of walk(dir).sort()) {
    hash.update(path.relative(dir, file).split(path.sep).join('/'))
    hash.update(hashFile(file))
  }
  return hash.digest('hex')
}

function loadTemplate(id) {
  const dir = path.join(TEMPLATES, id)
  const manifest = path.join(dir, 'module.json')
  if (!existsSync(manifest)) fail(`unknown extension template "${id}"`)
  return { dir, manifest: JSON.parse(readFileSync(manifest, 'utf8')) }
}

function installed() {
  const lock = readJSON(LOCKFILE, { schemaVersion: 1, extensions: {} })
  lock.extensions ??= {}
  return lock
}

function saveInstalled(lock) {
  writeJSON(LOCKFILE, lock)
}

function acquireLock() {
  if (existsSync(LOCK)) {
    const raw = readFileSync(LOCK, 'utf8').trim()
    const pid = Number(raw)
    let alive = false
    if (Number.isInteger(pid) && pid > 0) {
      try {
        process.kill(pid, 0)
        alive = true
      } catch {
        alive = false
      }
    }
    if (alive) fail(`another module command is running (pid ${raw})`)
    rmSync(LOCK, { force: true })
  }
  writeFileSync(LOCK, String(process.pid), { flag: 'wx' })
}

function releaseLock() {
  try {
    rmSync(LOCK, { force: true })
  } catch {
    // ignore
  }
}

function requireDependencies(manifest, lock) {
  for (const dep of manifest.requires ?? []) {
    if (dep === 'auth-core') continue
    if (!lock.extensions[dep]) fail(`extension ${manifest.id} requires ${dep}; install it first`)
  }
}

function dependents(id, lock) {
  return Object.entries(lock.extensions)
    .filter(([, entry]) => (entry.requires ?? []).includes(id))
    .map(([key]) => key)
}

function goImportsFor(manifest) {
  const oauth = new Set()
  const extensions = new Set()
  for (const item of manifest.copy ?? []) {
    if (!item.to.endsWith('.go')) continue
    const dir = path.dirname(item.to).split(path.sep).join('/')
    if (dir.startsWith('services/internal/auth/oauth/providers')) {
      oauth.add('internal/auth/oauth/providers')
    } else if (dir.startsWith('services/internal/extensions/')) {
      extensions.add(dir.replace(/^services\//, ''))
    }
  }
  return { oauth: [...oauth].sort(), extensions: [...extensions].sort() }
}

function generateGoRegistry(packageName, imports, generatedRel) {
  const lines = ['// Code generated by scripts/module.mjs. DO NOT EDIT.', `package ${packageName}`, '']
  if (imports.length > 0) {
    lines.push('import (')
    for (const imp of imports) lines.push(`\t_ "${MODULE}/${imp}"`)
    lines.push(')')
    lines.push('')
  }
  writeIfChanged(path.join(ROOT, generatedRel), `${lines.join('\n')}\n`)
}

function generateAuthzRegistry(entries) {
  const byImport = new Map()
  for (const entry of entries) {
    if (!entry.authzImport || !entry.authz?.length) continue
    const alias = entry.authzAlias || 'extv1'
    const current = byImport.get(entry.authzImport) ?? { alias, rules: [] }
    current.rules.push(...entry.authz.map((rule) => ({ ...rule, alias })))
    byImport.set(entry.authzImport, current)
  }
  const lines = ['// Code generated by scripts/module.mjs. DO NOT EDIT.', 'package authz', '']
  if (byImport.size > 0) {
    lines.push('import (')
    for (const [imp, value] of byImport) lines.push(`\t${value.alias} "${imp}"`)
    lines.push(')')
    lines.push('')
    lines.push('func init() {')
    for (const value of byImport.values()) {
      for (const rule of value.rules) {
        const op = `${rule.alias}.${rule.operation}`
        if (rule.public) lines.push(`\tRequirements[${op}] = Requirement{Public: true}`)
        else lines.push(`\tRequirements[${op}] = Requirement{Code: "${rule.code ?? ''}"}`)
      }
    }
    lines.push('}')
  } else {
    lines.push('func init() {}')
  }
  writeIfChanged(path.join(ROOT, GENERATED.authz), `${lines.join('\n')}\n`)
}

function generateFeatureRegistry(app, installedEntries) {
  const routes = []
  const menu = []
  const componentImports = new Map()
  for (const [id, entry] of Object.entries(installedEntries)) {
    const target = entry.targets?.[app]
    if (!target) continue
    for (const route of target.routes ?? []) {
      if (!route.path || !route.name || !route.component) continue
      const identifier = `${id}_${route.name}`.replace(/[^a-zA-Z0-9_]/g, '_')
      componentImports.set(identifier, `../${route.component.replace(/^\.?\//, '')}`)
      routes.push({ ...route, identifier })
    }
    for (const item of target.menu ?? []) {
      if (item) menu.push(item)
    }
  }

  const rel = app === 'admin' ? GENERATED.admin : GENERATED.web
  const lines = ['// Code generated by scripts/module.mjs. DO NOT EDIT.']
  lines.push("import type { RouteRecordRaw } from 'vue-router'")
  for (const [identifier, imp] of componentImports) {
    lines.push(`import ${identifier} from '${imp}'`)
  }
  lines.push('')
  lines.push('export const featureRoutes: RouteRecordRaw[] = [')
  for (const route of routes) {
    const meta = [`titleKey: ${JSON.stringify(route.titleKey ?? `nav.${route.name}`)}`]
    if (route.permission) meta.push(`permission: ${JSON.stringify(route.permission)}`)
    lines.push(
      `  { path: ${JSON.stringify(route.path)}, name: ${JSON.stringify(route.name)}, component: ${route.identifier}, meta: { ${meta.join(', ')} } },`,
    )
  }
  lines.push(']')
  lines.push('')
  lines.push('export const featureMenu = [')
  for (const item of menu) {
    const parts = [
      `label: ${JSON.stringify(item.label ?? '')}`,
      `path: ${JSON.stringify(item.path ?? '')}`,
    ]
    if (item.icon) parts.push(`icon: ${JSON.stringify(item.icon)}`)
    if (item.order !== undefined) parts.push(`order: ${item.order}`)
    if (item.permission) parts.push(`permission: ${JSON.stringify(item.permission)}`)
    lines.push(`  { ${parts.join(', ')} },`)
  }
  lines.push(']')
  lines.push('')
  writeIfChanged(path.join(ROOT, rel), `${lines.join('\n')}\n`)
}

function generateRegistries() {
  const lock = installed()
  const entries = Object.entries(lock.extensions)
  const oauthImports = new Set()
  const extensionImports = new Set()
  const authzEntries = []

  for (const [id, entry] of entries) {
    const { dir, manifest } = loadTemplate(id)
    const imports = goImportsFor(manifest)
    imports.oauth.forEach((imp) => oauthImports.add(imp))
    imports.extensions.forEach((imp) => extensionImports.add(imp))
    authzEntries.push({
      authzImport: manifest.authzImport,
      authzAlias: manifest.authzAlias,
      authz: manifest.authz,
    })
    void dir
    void entry
  }

  generateGoRegistry('oauthproviders_gen', [...oauthImports].sort(), GENERATED.oauth)
  generateGoRegistry('registry_gen', [...extensionImports].sort(), GENERATED.extensions)
  generateAuthzRegistry(authzEntries)
  generateFeatureRegistry('admin', lock.extensions)
  generateFeatureRegistry('web', lock.extensions)
}

function runGenerate() {
  const pnpm = process.platform === 'win32' ? 'pnpm.cmd' : 'pnpm'
  const result = spawnSync(pnpm, ['run', 'generate'], {
    cwd: ROOT,
    stdio: 'inherit',
    shell: process.platform === 'win32',
  })
  if (result.status !== 0) throw new Error('code generation failed')
}

function parseArgs(argv) {
  const flags = { dryRun: false, json: false, force: false, strict: false }
  const positional = []
  for (const arg of argv) {
    if (arg === '--') continue
    if (arg === '--dry-run') flags.dryRun = true
    else if (arg === '--json') flags.json = true
    else if (arg === '--force') flags.force = true
    else if (arg === '--strict') flags.strict = true
    else positional.push(arg)
  }
  return { flags, positional }
}

function add(id, flags) {
  const { dir, manifest } = loadTemplate(id)
  const lock = installed()
  if (lock.extensions[id]) fail(`extension ${id} is already installed`)
  requireDependencies(manifest, lock)

  const planned = (manifest.copy ?? []).map((item) => {
    const from = path.join(dir, item.from)
    const to = path.resolve(ROOT, item.to)
    if (!to.startsWith(ROOT + path.sep)) fail(`invalid destination ${item.to}`)
    if (!existsSync(from)) fail(`template file missing: ${item.from}`)
    if (existsSync(to) && !flags.force) fail(`destination already exists: ${item.to}`)
    return { from, to, rel: item.to, hash: hashFile(from) }
  })

  const plan = {
    action: 'add',
    id,
    version: manifest.version,
    codegen: Boolean(manifest.codegen),
    files: planned.map((item) => item.rel),
  }
  if (flags.json) console.log(JSON.stringify(plan, null, 2))
  else console.log(`install ${id}@${manifest.version}\n  ${planned.map((p) => p.rel).join('\n  ')}`)
  if (flags.dryRun) return

  acquireLock()
  const created = []
  try {
    rmSync(path.join(TMP, id), { recursive: true, force: true })
    for (const item of planned) {
      const staged = path.join(TMP, id, item.rel)
      mkdirSync(path.dirname(staged), { recursive: true })
      copyFileSync(item.from, staged)
    }
    for (const item of planned) {
      mkdirSync(path.dirname(item.to), { recursive: true })
      copyFileSync(path.join(TMP, id, item.rel), item.to)
      created.push(item.to)
    }
    const current = installed()
    current.extensions[id] = {
      version: manifest.version,
      kind: manifest.kind ?? 'feature',
      requires: manifest.requires ?? [],
      installedAt: new Date().toISOString(),
      baseHash: templateHash(dir),
      codegen: Boolean(manifest.codegen),
      generatedDirs: manifest.generatedDirs ?? [],
      files: planned.map((item) => ({ path: item.rel, hash: hashFile(item.to) })),
      generatedFiles: [
        GENERATED.oauth,
        GENERATED.extensions,
        GENERATED.authz,
        GENERATED.admin,
        GENERATED.web,
      ],
      targets: manifest.targets ?? {},
    }
    saveInstalled(current)
    generateRegistries()
    if (manifest.codegen) runGenerate()
  } catch (error) {
    for (const file of created) rmSync(file, { force: true })
    for (const dir of manifest.generatedDirs ?? []) {
      rmSync(path.join(ROOT, dir), { recursive: true, force: true })
    }
    const current = installed()
    delete current.extensions[id]
    saveInstalled(current)
    generateRegistries()
    throw error
  } finally {
    rmSync(path.join(TMP, id), { recursive: true, force: true })
    releaseLock()
  }
}

function remove(id, flags) {
  const lock = installed()
  const entry = lock.extensions[id]
  if (!entry) fail(`extension ${id} is not installed`)
  const blockers = dependents(id, lock)
  if (blockers.length > 0) fail(`cannot remove ${id}; required by ${blockers.join(', ')}`)

  const changed = (entry.files ?? []).filter(
    (file) => existsSync(path.join(ROOT, file.path)) && hashFile(path.join(ROOT, file.path)) !== file.hash,
  )
  if (changed.length > 0 && !flags.force) {
    fail(`refusing to remove ${id}; modified files: ${changed.map((f) => f.path).join(', ')} (use --force)`)
  }

  const plan = { action: 'remove', id, files: (entry.files ?? []).map((file) => file.path) }
  if (flags.json) console.log(JSON.stringify(plan, null, 2))
  else console.log(`remove ${id}\n  ${plan.files.join('\n  ')}`)
  if (flags.dryRun) return

  acquireLock()
  try {
    for (const file of entry.files ?? []) {
      rmSync(path.join(ROOT, file.path), { force: true })
      rmSync(path.join(ROOT, `${file.path}.new`), { force: true })
    }
    for (const dir of entry.generatedDirs ?? []) {
      rmSync(path.join(ROOT, dir), { recursive: true, force: true })
    }
    const current = installed()
    delete current.extensions[id]
    saveInstalled(current)
    generateRegistries()
    if (entry.codegen) runGenerate()
  } finally {
    releaseLock()
  }
}

function update(id, flags) {
  const { dir, manifest } = loadTemplate(id)
  const lock = installed()
  const entry = lock.extensions[id]
  if (!entry) fail(`extension ${id} is not installed`)

  const modified = new Set()
  for (const file of entry.files ?? []) {
    const full = path.join(ROOT, file.path)
    if (existsSync(full) && hashFile(full) !== file.hash) modified.add(file.path)
  }

  if (flags.json) {
    console.log(JSON.stringify({ action: 'update', id, version: manifest.version, modified: [...modified] }, null, 2))
  } else {
    console.log(`update ${id}: ${modified.size} modified file(s)`)
  }
  if (flags.dryRun) return

  acquireLock()
  try {
    for (const item of manifest.copy ?? []) {
      const from = path.join(dir, item.from)
      const to = path.join(ROOT, item.to)
      if (modified.has(item.to) && !flags.force) {
        copyFileSync(from, `${to}.new`)
        continue
      }
      mkdirSync(path.dirname(to), { recursive: true })
      copyFileSync(from, to)
    }
    const current = installed()
    current.extensions[id] = {
      ...entry,
      version: manifest.version,
      baseHash: templateHash(dir),
      files: (manifest.copy ?? []).map((item) => ({
        path: item.to,
        hash: existsSync(path.join(ROOT, item.to)) ? hashFile(path.join(ROOT, item.to)) : '',
      })),
      targets: manifest.targets ?? {},
    }
    saveInstalled(current)
    generateRegistries()
    if (manifest.codegen) runGenerate()
  } finally {
    releaseLock()
  }
}

function list(flags) {
  const lock = installed()
  const available = existsSync(TEMPLATES)
    ? readdirSync(TEMPLATES, { withFileTypes: true })
        .filter((entry) => entry.isDirectory())
        .map((entry) => {
          const manifest = readJSON(path.join(TEMPLATES, entry.name, 'module.json'), null)
          return manifest ? { id: entry.name, version: manifest.version, kind: manifest.kind ?? 'feature' } : null
        })
        .filter(Boolean)
    : []
  const result = {
    available,
    installed: Object.entries(lock.extensions).map(([id, entry]) => ({
      id,
      version: entry.version,
      kind: entry.kind,
      requires: entry.requires ?? [],
      files: (entry.files ?? []).length,
    })),
  }
  if (flags.json) {
    console.log(JSON.stringify(result, null, 2))
    return
  }
  console.log('Available:')
  for (const item of result.available) console.log(`  ${item.id}@${item.version} (${item.kind})`)
  console.log('Installed:')
  if (result.installed.length === 0) console.log('  (none)')
  for (const item of result.installed) {
    console.log(`  ${item.id}@${item.version} (${item.kind}) ${item.requires.length ? `requires ${item.requires.join(',')}` : ''}`)
  }
}

function checkUpstream(flags) {
  const config = readJSON(UPSTREAM, {})
  const report = []
  for (const [name, item] of Object.entries(config)) {
    const result = { name, repo: item.repo, ref: item.ref, pinned: item.commit, remote: null, status: 'offline', checkedAt: new Date().toISOString() }
    if (item.repo && item.ref) {
      const proc = spawnSync('git', ['ls-remote', item.repo, item.ref], {
        encoding: 'utf8',
        timeout: 15000,
      })
      if (proc.status === 0 && proc.stdout.trim()) {
        result.remote = proc.stdout.trim().split(/\s+/)[0]
        result.status = item.commit && item.commit === result.remote ? 'up-to-date' : 'outdated'
      }
    }
    report.push(result)
  }

  const payload = { status: report.every((r) => r.status === 'offline') ? 'offline' : report.some((r) => r.status === 'outdated') ? 'outdated' : 'up-to-date', report }
  if (flags.json) console.log(JSON.stringify(payload, null, 2))
  else {
    for (const item of report) {
      console.log(`${item.name}: ${item.status} (pinned=${item.pinned ?? 'unset'}, remote=${item.remote ?? 'unknown'})`)
    }
  }

  const lines = ['# Upstream reference report', '', `Generated: ${new Date().toISOString()}`, '']
  for (const item of report) {
    lines.push(`## ${item.name}`)
    lines.push(`- repo: ${item.repo}`)
    lines.push(`- ref: ${item.ref}`)
    lines.push(`- pinned: ${item.pinned ?? 'unset'}`)
    lines.push(`- remote: ${item.remote ?? 'unknown'}`)
    lines.push(`- status: ${item.status}`)
    lines.push('')
  }
  writeIfChanged(path.join(EXT_DIR, 'upstream-report.md'), `${lines.join('\n')}\n`)

  if (flags.strict && payload.status !== 'up-to-date') process.exit(1)
}

function main() {
  const { flags, positional } = parseArgs(process.argv.slice(2))
  const [command, id] = positional
  try {
    switch (command) {
      case 'add':
        if (!id) fail('usage: module.mjs add <id>')
        add(id, flags)
        break
      case 'remove':
        if (!id) fail('usage: module.mjs remove <id>')
        remove(id, flags)
        break
      case 'update':
        if (!id) fail('usage: module.mjs update <id>')
        update(id, flags)
        break
      case 'list':
        list(flags)
        break
      case 'check-upstream':
        checkUpstream(flags)
        break
      default:
        fail('usage: module.mjs <add|remove|update|list|check-upstream> [id] [--dry-run] [--json] [--force] [--strict]')
    }
  } catch (error) {
    fail(error instanceof Error ? error.message : String(error))
  }
}

main()
