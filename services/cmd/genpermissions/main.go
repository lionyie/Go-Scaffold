// Command genpermissions renders the permission catalog into Go and TypeScript
// so both sides of the stack stay in sync.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"
)

type entry struct {
	Code     string `yaml:"code"`
	Name     string `yaml:"name"`
	Resource string `yaml:"resource"`
	Action   string `yaml:"action"`
}

type spec struct {
	Permissions []entry `yaml:"permissions"`
}

func main() {
	specPath := flag.String("spec", "../contracts/permissions.yaml", "permission catalog path")
	goOut := flag.String("go-out", "internal/pkg/rbac/permissions_gen.go", "generated Go path")
	tsOut := flag.String("ts-out", "../packages/shared/src/permissions.gen.ts", "generated TypeScript path")
	flag.Parse()

	raw, err := os.ReadFile(*specPath)
	if err != nil {
		fatal(err)
	}
	var s spec
	if err := yaml.Unmarshal(raw, &s); err != nil {
		fatal(err)
	}
	if len(s.Permissions) == 0 {
		fatal(fmt.Errorf("no permissions found"))
	}

	if err := writeFile(*goOut, goSource(s.Permissions)); err != nil {
		fatal(err)
	}
	if err := writeFile(*tsOut, tsSource(s.Permissions)); err != nil {
		fatal(err)
	}
}

func goSource(entries []entry) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/genpermissions. DO NOT EDIT.\n\npackage rbac\n\n")
	b.WriteString("const (\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "\t%s = %q\n", constName(e.Code), e.Code)
	}
	b.WriteString(")\n\n")

	b.WriteString("// PermissionDef is a single entry of the permission catalog.\ntype PermissionDef struct {\n\tCode string\n\tName string\n\tResource string\n\tAction string\n}\n\n")
	b.WriteString("// Catalog returns every built-in permission.\nfunc Catalog() []PermissionDef {\n\treturn []PermissionDef{\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "\t\t{%s, %q, %q, %q},\n", constName(e.Code), e.Name, e.Resource, e.Action)
	}
	b.WriteString("\t}\n}\n\n")

	b.WriteString("// All returns every built-in permission code.\nfunc All() []string {\n\treturn []string{\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "\t\t%s,\n", constName(e.Code))
	}
	b.WriteString("\t}\n}\n")

	formatted, err := format.Source(b.Bytes())
	if err != nil {
		fatal(fmt.Errorf("format generated Go: %w", err))
	}
	return formatted
}

func tsSource(entries []entry) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/genpermissions. DO NOT EDIT.\n\n")
	b.WriteString("export const Permission = {\n")
	for _, e := range entries {
		key := strings.TrimPrefix(constName(e.Code), "Perm")
		fmt.Fprintf(&b, "  %s: %q,\n", key, e.Code)
	}
	b.WriteString("} as const\n\n")
	b.WriteString("export type PermissionCode = (typeof Permission)[keyof typeof Permission]\n\n")
	b.WriteString("export const AllPermissions: PermissionCode[] = Object.values(Permission)\n")
	return b.Bytes()
}

func constName(code string) string {
	parts := strings.FieldsFunc(code, func(r rune) bool {
		return r == ':' || r == '-' || r == '.' || r == '_'
	})
	var b strings.Builder
	b.WriteString("Perm")
	for _, part := range parts {
		if part == "" {
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]))
		b.WriteString(part[1:])
	}
	return b.String()
}

func writeFile(path string, content []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, content, 0o644)
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "genpermissions:", err)
	os.Exit(1)
}
